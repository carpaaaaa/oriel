#!/usr/bin/env python3
"""Settings' area B, tabs (studio/08 B): each row changed, its effect seen.
  - Open sized pop-ups in small windows (tabs.popupWindows, studio/01 §3.35)
  - ⌘Z reopens a closed tab (tabs.undoReopens, §9.19)
  - ⌘-click on a pin opens a new tab (pins.commandNewTab, §6.13)
  - Close tabs you leave alone (tabs.close.after, §9.32-§9.36) and the archive
  - Keep selected sites awake (tabs.keepAwake note, §9.24)
  - Confirm before quitting (quit.confirm, §1.11)"""
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bench as b  # noqa: E402
import tabs_kit as k  # noqa: E402

t = b.T()
k.world("settings-b-tabs")
k.launch()
CTRL = "control"

# Open sized pop-ups in small windows (§3.35): off, a tab that keeps its opener.
a = k.page("opener")
b.ev(a, f"window.pop = window.open('{k.url('popup')}', 'p', 'width=400,height=300'); true")
b.wait_for(lambda: (x := k.active()) and k.name_of(x["url"]) == "popup" and not x["loading"], within=20, what="pop-up tab")
pop = k.active()
t.ok(pop.get("popup") and pop.get("opener") == a and pop["label"] == "127.0.0.1", "off: a sized pop-up is a tab, named by its site")
t.ok(b.ev(pop["id"], "!!window.opener") is True, "and the page that opened it can still talk to it (window.opener)")
t.ok(b.ev(a, "!!window.pop && !window.pop.closed") is True, "both ways")
k.cmd("tab.close", id=pop["id"]); k.settle()
k.cmd("prefs.set", key="tabs.popupWindows", value=True)
tabs_before = len(k.tabs())
b.ev(a, f"window.open('{k.url('popup2')}', 'q', 'width=400,height=300'); true")
b.wait_for(lambda: any("popup2" in w["url"] for w in b.call({"do": "settingsb.popupWindows"})["windows"]), within=20, what="pop-up window")
w = next(w for w in b.call({"do": "settingsb.popupWindows"})["windows"] if "popup2" in w["url"])
t.ok(len(k.tabs()) == tabs_before, "on: no tab for it")
t.ok(w["bounds"]["width"] == 400 and w["bounds"]["height"] == 300, "its own window, at the size it asked for")
k.cmd("prefs.set", key="tabs.popupWindows", value=False)

# ⌘Z reopens a closed tab (§9.19)
z = k.page("zed")
k.cmd("tab.close", id=z); k.settle()
b.key("Z", CTRL); k.settle(0.6)
t.ok(k.by_name("zed") is None, "off: ⌘Z does nothing to tabs")
k.cmd("prefs.set", key="tabs.undoReopens", value=True)
z = k.page("zed2")
k.cmd("tab.close", id=z); k.settle()
b.key("Z", CTRL); k.settle(0.8)
t.ok(k.by_name("zed2") is not None and k.name_of(k.active()["url"]) == "zed2", "on: ⌘Z right after closing brings it back, in front")
b.key("Z", CTRL); k.settle(0.6)
t.ok(len([x for x in k.tabs() if k.name_of(x["url"]) == "zed2"]) == 1, "once only")
z3 = k.page("zed3")
k.cmd("tab.close", id=z3); k.settle()
b.key("A"); k.settle(0.3)
b.key("Z", CTRL); k.settle(0.6)
t.ok(k.by_name("zed3") is None, "anything typed after the close: ⌘Z undoes as before")
z4 = k.page("zed4")
k.cmd("tab.close", id=z4); k.settle()
b.mouse(5, 300); k.settle(0.3)
b.key("Z", CTRL); k.settle(0.6)
t.ok(k.by_name("zed4") is None, "a click after the close: the same")
k.cmd("prefs.set", key="tabs.undoReopens", value=False)

# ⌘-click on a pin opens a new tab (§6.13)
p = k.page("home")
k.cmd("tab.pin", id=p); k.settle()
pinID = k.tab(p)["pinID"]
other = k.page("other")
k.cmd("pin.commandClick", id=p); k.settle(0.4)
t.ok(p in k.win()["picked"], "off: ⌘-click picks the pin, as any tab")
k.cmd("tab.pick", id=p, mode="clear")
k.cmd("prefs.set", key="pins.commandNewTab", value=True)
n = k.cmd("pin.commandClick", id=p); k.settle(0.6)
x = k.tab(n)
t.ok(x and not x.get("pinID") and k.name_of(x["url"]) == "home" and k.win()["activeID"] == other, "on, at home: its page in a new tab, behind")
k.cmd("tab.select", id=p); k.settle(0.3)
b.ev(p, f"location.href = '{k.url('away')}'; true")
b.wait_for(lambda: k.tab(p)["title"] == "away", what="pin wandered")
fresh = k.cmd("pin.commandClick", id=p); k.settle(0.8)
wandered, pin = k.tab(p), k.tab(fresh)
t.ok(wandered and not wandered.get("pinID") and k.name_of(wandered["url"]) == "away", "wandered: its page kept as a loose tab")
t.ok(pin and pin.get("pinID") == pinID and k.name_of(pin["url"]) == "home" and k.win()["activeID"] == fresh, "and the pin a fresh tab at home, in front")
t.ok(k.tabs()[0]["id"] == fresh and [x["id"] for x in k.tabs()].index(p) == 1, "the pin in its place, the page first among the loose tabs")
k.cmd("prefs.set", key="pins.commandNewTab", value=False)

# Close tabs you leave alone (§9.32-§9.36)
for x in [x["id"] for x in k.tabs() if not x.get("pinID")]:
    k.cmd("tab.close", id=x)
old1 = k.page("old1"); old2 = k.page("old2")
named = k.page("named"); k.cmd("tab.rename", id=named, name="Keep me")
g = k.page("grouped"); k.cmd("group.new", ids=[g])
# Another site: Keep This Site Awake goes by the host, and every other page here is 127.0.0.1.
awake = k.cmd("tab.open", url=k.BASE.replace("127.0.0.1", "localhost") + "/awake", foreground=True)
b.wait_for(lambda: k.tab(awake)["title"] == "awake", what="awake page")
front = k.page("front")
for x in (old1, old2, named, g, awake, fresh):
    b.call({"do": "tabs.age", "id": x, "seconds": 13 * 3600})
t.ok(b.call({"do": "settingsb.closeLeftAlone"})["closed"] == [], "Never, as it comes: nothing closes however long it is left")
k.cmd("prefs.set", key="tabs.close.after", value=12)
k.cmd("tab.keepAwake", id=awake, on=True); k.settle(0.2)
closed = b.call({"do": "settingsb.closeLeftAlone"})["closed"]
t.ok(sorted(closed) == sorted([old1, old2]), "After 12 hours: the tabs left that long close")
s = k.st()
t.ok(all(k.tab(x, s) for x in (named, g, awake, fresh, front)), "pinned, named, grouped, a site kept awake and the tab in front stay")
t.ok(b.call({"do": "settingsb.stays", "id": awake})["reason"] == "kept awake for this site", "Keep This Site Awake keeps it")
t.ok(b.call({"do": "tabs.awake", "id": awake})["reason"] == "kept awake for this site", "from sleep too")
k.settle(0.5)
arch = k.read("archive.json")
t.ok(arch and [k.name_of(x["url"]) for x in arch][:2] in (["old2", "old1"], ["old1", "old2"]), "into the archive (archive.json)")
t.ok(set(arch[0]) == {"id", "url", "title", "closed"} and arch[0]["closed"].endswith("Z") and "." not in arch[0]["closed"], "the Mac's keys, dates in ISO 8601")
t.ok(k.win()["reopenTitle"] == "Reopen Closed Tab", "⇧⌘T can bring them back")
# History › Archived Tabs…
k.cmd("history.archive"); k.settle(1.0)
page = k.active()
b.wait_for(lambda: b.ev(page["id"], "document.querySelectorAll('[data-archived]').length") == 2, what="archive page")
t.ok(page.get("internal") == "archive" and page["label"] == "Archived Tabs", "History › Archived Tabs… lists them")
b.ev(page["id"], "document.querySelector('[data-archived] .hp-go').click(); true"); k.settle(0.8)
t.ok(len(b.call({"do": "settingsb.archive"})["archive"]) == 1 and k.name_of(k.active()["url"]) in ("old1", "old2"), "a click opens one again, out of the archive")
k.cmd("tab.keepAwake", id=awake, on=False); k.settle(1.0)
t.ok(k.read("prefs.json").get("tabs.awakeSites", []) == [], "Keep This Site Awake off: the site off the list")

# At launch, last night's due tabs go before anyone looks (Browser.init).
late = k.page("late")
k.page("front2")
b.call({"do": "tabs.age", "id": late, "seconds": 13 * 3600})
b.call({"do": "tabs.write"})
k.relaunch()
b.wait_for(lambda: k.by_name("late") is None, within=20, what="late closed at launch")
t.ok(any(k.name_of(x["url"]) == "late" for x in b.call({"do": "settingsb.archive"})["archive"]), "a tab due while Oriel was quit closes at launch, into the archive")

# Confirm before quitting (§1.11)
k.cmd("prefs.set", key="quit.confirm", value=True)
b.call({"do": "settingsb.quitAnswer", "answer": "cancel"})
r = k.cmd("app.quit"); time.sleep(1.5)
t.ok(r == {"quit": False} and b.call({"do": "settingsb.quitAsked"})["asked"] == 1 and b.PROC.poll() is None, "on: Quit Oriel? asked; Cancel keeps it open")
b.call({"do": "settingsb.quitAnswer", "answer": "quit"})
r = k.cmd("app.quit")
b.wait_for(lambda: b.PROC.poll() is not None, within=20, what="quit")
t.ok(r == {"quit": True}, "Quit quits")

# Alt+F4, Windows' way to quit: the last window asks, another only closes.
k.launch()
k.cmd("prefs.set", key="quit.confirm", value=True)
asked = lambda: b.call({"do": "settingsb.quitAsked"})["asked"]
alt_f4 = lambda wid=None: b.call({"do": "key", "key": "F4", "modifiers": ["alt"], **({"window": wid} if wid else {})})
b.call({"do": "settingsb.quitAnswer", "answer": "cancel"})
alt_f4(); time.sleep(1.5)
t.ok(asked() == 1 and b.PROC.poll() is None and len(b.state()["windows"]) == 1, "on: Alt+F4 on the last window asks Quit Oriel?; Cancel keeps it open")
first = k.wid(0)
k.cmd("window.new")
b.wait_for(lambda: len(b.state()["windows"]) == 2, what="a second window")
second = next(w["id"] for w in k.st()["windows"] if w["id"] != first)
alt_f4(second)
b.wait_for(lambda: len(b.state()["windows"]) == 1, what="Alt+F4 closes that window")
t.ok(asked() == 1 and k.wid(0) == first, "Alt+F4 on a window that isn't the last closes it without asking")
b.call({"do": "settingsb.quitAnswer", "answer": "quit"})
alt_f4()
b.wait_for(lambda: b.PROC.poll() is not None, within=20, what="Alt+F4, Quit")
t.ok(True, "Alt+F4 on the last window, Quit: Oriel quits")
k.launch()
k.cmd("prefs.set", key="quit.confirm", value=False)
r = k.cmd("app.quit")
b.wait_for(lambda: b.PROC.poll() is not None, within=20, what="quit without asking")
t.ok(r == {"quit": True}, "off: Ctrl+Shift+Q quits without asking")
t.done()
