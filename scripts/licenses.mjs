// Writes THIRD_PARTY_LICENSES.md: every package that ships inside the app
// (production dependencies, all levels), with its license text, or, for a
// package that carries none, the license's name, a link to its official text
// and where the source is (studio/09 §6).
//   npm run licenses
//   node scripts/licenses.mjs --out <file> --expect <name>,<name>
// --expect fails when a package isn't there (the release checks koffi's
// Windows binaries, installed just before for both architectures).
import { execSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'

const arg = name => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : undefined }
const outFile = arg('--out') ?? 'THIRD_PARTY_LICENSES.md'
const expected = (arg('--expect') ?? '').split(',').filter(Boolean)

// npm ls exits non-zero for extraneous packages (koffi's binary for the
// other architecture, installed with --no-save); its JSON is still right.
let listing
try { listing = execSync('npm ls --omit=dev --all --json', { encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'ignore'] }) }
catch (e) { listing = e.stdout }
const tree = JSON.parse(listing)
const seen = new Map()
const add = (name, version) => { if (version && !seen.has(`${name}@${version}`)) seen.set(`${name}@${version}`, { name, version }) }
const walk = deps => {
  for (const [name, d] of Object.entries(deps ?? {})) {
    add(name, d.version)
    walk(d.dependencies)
  }
}
walk(tree.dependencies)
// koffi's prebuilt binaries are optional packages: whichever are installed
// ship, listed or not.
const scope = path.join('node_modules', '@koromix')
if (existsSync(scope)) {
  for (const dir of readdirSync(scope)) {
    const pkg = path.join(scope, dir, 'package.json')
    if (dir.startsWith('koffi-') && existsSync(pkg)) add(`@koromix/${dir}`, JSON.parse(readFileSync(pkg, 'utf8')).version)
  }
}

/** The official text of a license, by its SPDX name. */
const official = {
  'MIT': 'https://opensource.org/license/mit',
  'MPL-2.0': 'https://www.mozilla.org/en-US/MPL/2.0/',
  'Apache-2.0': 'https://www.apache.org/licenses/LICENSE-2.0',
  'ISC': 'https://opensource.org/license/isc-license-txt',
  'BSD-2-Clause': 'https://opensource.org/license/bsd-2-clause',
  'BSD-3-Clause': 'https://opensource.org/license/bsd-3-clause',
  'OFL-1.1': 'https://openfontlicense.org/open-font-license-official-text/',
  'BlueOak-1.0.0': 'https://blueoakcouncil.org/license/1.0.0',
}
const linkFor = id => official[id] ?? `https://spdx.org/licenses/${encodeURIComponent(id)}.html`

const repoOf = pkg => {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  if (!r) return pkg.homepage ?? null
  if (/^[\w.-]+\/[\w.-]+$/.test(r)) return `https://github.com/${r}`
  return r.replace(/^git\+/, '').replace(/^git@github\.com:/, 'https://github.com/').replace(/^ssh:\/\/git@/, 'https://').replace(/\.git$/, '')
}

const out = ['# Third-party licenses', '', 'Everything below ships inside Oriel. Generated by `npm run licenses`; do not edit by hand.', '']
const missing = []
for (const { name, version } of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const dir = path.join('node_modules', name)
  if (!existsSync(dir)) { missing.push(name); continue }
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'see the package'
  const file = readdirSync(dir).find(f => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  out.push(`## ${name} ${version}`, '', `License: ${license}`, '')
  if (file) { out.push('```', readFileSync(path.join(dir, file), 'utf8').trim(), '```', ''); continue }
  // No text in the package: the license's own, and where the source is.
  const ids = license.replace(/[()]/g, ' ').split(/\s+(?:OR|AND)\s+|\s+/).filter(x => x && !/^(OR|AND|WITH)$/.test(x))
  out.push(`The package carries no license file. ${ids.map(id => `${id}: ${linkFor(id)}`).join('; ')}.`)
  const repo = repoOf(pkg)
  if (repo) out.push(`Source: ${repo}`)
  out.push('')
}
writeFileSync(outFile, out.join('\n'))
console.log(`${seen.size} packages`)
const absent = expected.filter(e => ![...seen.values()].some(s => s.name === e) || missing.includes(e))
if (absent.length) { console.error(`missing: ${absent.join(', ')}`); process.exit(1) }
